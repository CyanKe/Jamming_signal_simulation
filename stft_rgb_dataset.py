#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""
stft_rgb_dataset.py - PyTorch Dataset for STFT RGB colormap data

Loads RGB colormap representations of STFT spectrograms generated by MATLAB
(see utils/apply_colormap_to_stft.m and utils/convert_stft_to_rgb.m).

Supports three modes for using multiple colormap variants as data augmentation:

    'single'  - Load one specific colormap, each sample returned once.
                Dataset length = N (original sample count).

    'expand'  - Treat each colormap variant as an independent sample.
                Dataset length = N × C (samples × colormaps).
                Use this for offline dataset expansion / pre-augmentation.

    'augment' - Each sample randomly picks a colormap on __getitem__.
                Dataset length = N. Different epochs see different colormaps.
                Use this for online data augmentation during training.

Usage:
    # Single colormap
    ds = STFTColormapDataset('test_echo_stfts_rgb.mat', 'test_echo_metadata.json',
                             colormap='jet', mode='single')
    img, label = ds[0]  # img: [3, H, W] float32 in [0, 1]

    # Expand: all colormaps as independent samples
    ds = STFTColormapDataset('test_echo_stfts_rgb.mat', 'test_echo_metadata.json',
                             mode='expand')
    print(len(ds))  # N × num_colormaps

    # Augment: random colormap per sample per epoch
    ds = STFTColormapDataset('test_echo_stfts_rgb.mat', 'test_echo_metadata.json',
                             mode='augment')
    loader = DataLoader(ds, batch_size=32, shuffle=True)
"""

import json
import argparse
import random
from pathlib import Path

import numpy as np
import torch
from torch.utils.data import Dataset, DataLoader

# Import loading utilities from umap_stft
from umap_stft import load_stft_rgb, list_rgb_colormaps, load_metadata, normalize_label


def _get_labels_from_metadata(metadata):
    """Extract label strings from metadata list."""
    labels = []
    for item in metadata:
        jt = item['jam_types']
        if isinstance(jt, list):
            labels.append(normalize_label('+'.join(sorted(jt))))
        else:
            labels.append(normalize_label(jt))
    return labels


def _encode_labels(labels):
    """Encode string labels to integer indices."""
    unique_labels = sorted(set(labels))
    label_to_idx = {l: i for i, l in enumerate(unique_labels)}
    encoded = [label_to_idx[l] for l in labels]
    return torch.tensor(encoded, dtype=torch.long), label_to_idx


class STFTColormapDataset(Dataset):
    """PyTorch Dataset for STFT RGB colormap spectrograms.

    Each sample is a 3-channel RGB image [3, H, W] in float32 [0, 1] format,
    suitable for standard torchvision transforms (Normalize, RandomCrop, etc.).

    Args:
        rgb_path: Path to *_echo_stfts_rgb.mat file.
        metadata_path: Path to matching *_echo_metadata.json file.
        colormap: Colormap name for 'single' mode (default: 'jet').
                  Ignored in 'expand' and 'augment' modes.
        mode: 'single' | 'expand' | 'augment' (default: 'single').
        transform: Optional torchvision transform / albumentations callable.
        seed: Random seed for reproducible 'augment' mode (default: None).
    """

    def __init__(self, rgb_path, metadata_path=None,
                 colormap='jet', mode='single',
                 transform=None, seed=None):
        self.rgb_path = rgb_path
        self.mode = mode
        self.transform = transform

        if mode not in ('single', 'expand', 'augment'):
            raise ValueError(f"mode must be 'single', 'expand', or 'augment', got '{mode}'")

        # --- Discover available colormaps ---
        self.colormap_names = list_rgb_colormaps(rgb_path)
        if not self.colormap_names:
            raise ValueError(f"No colormap data found in {rgb_path}")
        self.num_colormaps = len(self.colormap_names)

        # --- Load all colormap data lazily (loaded on first access) ---
        self._data = None  # dict: {name: np.ndarray [N, H, W, 3] uint8}

        # --- Validate and set colormap for 'single' mode ---
        if mode == 'single':
            if colormap not in self.colormap_names:
                raise ValueError(
                    f"Colormap '{colormap}' not found. Available: {self.colormap_names}"
                )
            self.colormap_index = self.colormap_names.index(colormap)
        else:
            self.colormap_index = None

        # --- Load metadata and labels ---
        self.labels = None
        self.label_map = None
        self.num_classes = None
        if metadata_path and Path(metadata_path).exists():
            with open(metadata_path, 'r', encoding='utf-8') as f:
                metadata = json.load(f)
            labels_str = _get_labels_from_metadata(metadata)
            self.labels, self.label_map = _encode_labels(labels_str)
            self.num_classes = len(self.label_map)
        else:
            # Dummy labels for unsupervised use
            self.num_samples = self._get_num_samples()
            self.labels = torch.zeros(self.num_samples, dtype=torch.long)

        # --- Random state for 'augment' mode ---
        self.rng = random.Random(seed) if seed is not None else random

        # --- Print info ---
        n = self._get_num_samples()
        print(f'STFTColormapDataset: {rgb_path}')
        print(f'  Mode: {mode}, Colormaps: {self.colormap_names}')
        print(f'  Samples: {n}, Classes: {self.num_classes}')
        if self.labels is not None and self.label_map:
            print(f'  Label map: {self.label_map}')

    def _load_data(self):
        """Lazy-load all colormap RGB data from .mat file."""
        if self._data is None:
            self._data = load_stft_rgb(self.rgb_path, colormap_name=None)
            # Verify all arrays have consistent dimensions
            shapes = {k: v.shape for k, v in self._data.items()}
            if len(set(shapes.values())) > 1:
                print(f'Warning: Inconsistent shapes across colormaps: {shapes}')

    def _get_num_samples(self):
        """Get the number of original samples (N, not counting colormap expansion)."""
        # Peek at first colormap to get sample count
        data = load_stft_rgb(self.rgb_path, colormap_name=self.colormap_names[0])
        return data.shape[0]

    @property
    def num_original_samples(self):
        return self._get_num_samples()

    def __len__(self):
        n = self._get_num_samples()
        if self.mode == 'expand':
            return n * self.num_colormaps
        return n

    def __getitem__(self, idx):
        self._load_data()

        if self.mode == 'expand':
            sample_idx = idx // self.num_colormaps
            cmap_idx = idx % self.num_colormaps
        elif self.mode == 'augment':
            sample_idx = idx
            cmap_idx = self.rng.randint(0, self.num_colormaps - 1)
        else:  # single
            sample_idx = idx
            cmap_idx = self.colormap_index

        cmap_name = self.colormap_names[cmap_idx]
        rgb = self._data[cmap_name][sample_idx]  # [H, W, 3] uint8

        # Convert to torch: [H, W, 3] uint8 -> [3, H, W] float32 in [0, 1]
        rgb = torch.from_numpy(rgb).permute(2, 0, 1).float() / 255.0

        if self.transform:
            rgb = self.transform(rgb)

        label = self.labels[sample_idx] if self.labels is not None else 0
        return rgb, label

    def get_colormap_names(self):
        """Return list of available colormap names."""
        return list(self.colormap_names)


def main():
    parser = argparse.ArgumentParser(
        description='Load STFT RGB colormap data into PyTorch DataLoader')
    parser.add_argument('--rgb_path', type=str, required=True,
                        help='Path to *_echo_stfts_rgb.mat file')
    parser.add_argument('--metadata_path', type=str, default=None,
                        help='Path to matching *_echo_metadata.json file')
    parser.add_argument('--colormap', type=str, default='jet',
                        help='Colormap for single mode (default: jet)')
    parser.add_argument('--mode', type=str, default='single',
                        choices=['single', 'expand', 'augment'],
                        help='Dataset mode (default: single)')
    parser.add_argument('--batch_size', type=int, default=32,
                        help='Batch size for DataLoader')
    parser.add_argument('--info', action='store_true', default=True,
                        help='Print dataset statistics')
    args = parser.parse_args()

    # Auto-detect metadata if not provided
    meta_path = args.metadata_path
    if meta_path is None:
        candidate = args.rgb_path.replace('_stfts_rgb.mat', '_metadata.json')
        if Path(candidate).exists():
            meta_path = candidate

    dataset = STFTColormapDataset(
        args.rgb_path, meta_path,
        colormap=args.colormap, mode=args.mode,
    )

    dataloader = DataLoader(dataset, batch_size=args.batch_size, shuffle=True)

    if args.info:
        print(f'\n--- Dataset Info ---')
        print(f'  Length: {len(dataset)}')
        print(f'  Colormaps: {dataset.get_colormap_names()}')
        if dataset.label_map:
            print(f'  Classes: {dataset.num_classes}')
            print(f'  Label map: {dataset.label_map}')

        print(f'\n--- Batch Inspection ---')
        for batch in dataloader:
            imgs, labels = batch
            print(f'  Image batch: {imgs.shape}  (expected [B, 3, H, W])')
            print(f'  Label batch: {labels.shape}')
            print(f'  Image range: [{imgs.min().item():.3f}, {imgs.max().item():.3f}]')
            print(f'  Image dtype: {imgs.dtype}')
            print(f'  Labels: {labels.tolist()}')
            break

    # Example: build a simple CNN classifier
    H = imgs.shape[2]
    W = imgs.shape[3]
    num_classes = dataset.num_classes if dataset.num_classes else 2

    # A minimal CNN for spectrogram classification
    model = torch.nn.Sequential(
        torch.nn.Conv2d(3, 32, kernel_size=3, padding=1),
        torch.nn.ReLU(),
        torch.nn.MaxPool2d(2),
        torch.nn.Conv2d(32, 64, kernel_size=3, padding=1),
        torch.nn.ReLU(),
        torch.nn.MaxPool2d(2),
        torch.nn.Conv2d(64, 128, kernel_size=3, padding=1),
        torch.nn.ReLU(),
        torch.nn.AdaptiveAvgPool2d((1, 1)),
        torch.nn.Flatten(),
        torch.nn.Linear(128, 64),
        torch.nn.ReLU(),
        torch.nn.Dropout(0.3),
        torch.nn.Linear(64, num_classes),
    )
    print(f'\n--- Example CNN Classifier ---')
    print(f'  Input: [B, 3, {H}, {W}]')
    print(f'  Output: [B, {num_classes}]')
    print(f'  Model:\n    {model}')


if __name__ == '__main__':
    main()
